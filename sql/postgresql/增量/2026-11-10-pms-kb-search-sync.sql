-- 在 pms_knowledge_document 所在 schema 执行。保留旧版本触发器，供旧 JAR 回退使用。
BEGIN;

CREATE TABLE IF NOT EXISTS pms_kb_search_sync (
    tenant_id bigint NOT NULL,
    document_id bigint NOT NULL,
    version bigint GENERATED BY DEFAULT AS IDENTITY,
    force_rebuild boolean NOT NULL DEFAULT false,
    failures integer NOT NULL DEFAULT 0,
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, document_id)
);
CREATE INDEX IF NOT EXISTS idx_pms_kb_search_sync_due
    ON pms_kb_search_sync (next_attempt_at, document_id, tenant_id);

-- document_id=0 是每个范围的索引维护任务，初始化时要求全量重建一次。
INSERT INTO pms_kb_search_sync (tenant_id, document_id, force_rebuild)
SELECT tenant_id, 0, true FROM (
    SELECT DISTINCT tenant_id FROM pms_knowledge_document
    UNION SELECT 0
) tenants
ON CONFLICT (tenant_id, document_id) DO NOTHING;

CREATE OR REPLACE FUNCTION pms_kb_enqueue_search_sync() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    old_tenant bigint;
    old_id bigint;
    new_tenant bigint;
    new_id bigint;
BEGIN
    IF TG_OP <> 'INSERT' THEN
        old_tenant := OLD.tenant_id;
        old_id := OLD.id;
    END IF;
    IF TG_OP <> 'DELETE' THEN
        new_tenant := NEW.tenant_id;
        new_id := NEW.id;
    END IF;

    EXECUTE format(
        'INSERT INTO %I.pms_kb_search_sync (tenant_id, document_id)
         SELECT DISTINCT tenant_id, 0 FROM unnest($1::bigint[]) AS tenants(tenant_id)
         WHERE tenant_id IS NOT NULL ORDER BY tenant_id
         ON CONFLICT (tenant_id, document_id) DO NOTHING', TG_TABLE_SCHEMA)
    USING ARRAY[old_tenant, new_tenant];

    EXECUTE format(
        'INSERT INTO %I.pms_kb_search_sync (tenant_id, document_id)
         SELECT DISTINCT tenant_id, document_id FROM (VALUES ($1::bigint, $2::bigint), ($3::bigint, $4::bigint)) AS docs(tenant_id, document_id)
         WHERE tenant_id IS NOT NULL AND document_id IS NOT NULL ORDER BY tenant_id, document_id
         ON CONFLICT (tenant_id, document_id) DO UPDATE
         SET version = EXCLUDED.version, failures = 0, next_attempt_at = now()', TG_TABLE_SCHEMA)
    USING old_tenant, old_id, new_tenant, new_id;

    RETURN NULL;
END;
$$;

CREATE OR REPLACE FUNCTION pms_kb_enqueue_search_truncate() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    EXECUTE format(
        'INSERT INTO %1$I.pms_kb_search_sync (tenant_id, document_id, force_rebuild)
         SELECT tenant_id, 0, true FROM (
             SELECT DISTINCT tenant_id FROM %1$I.pms_knowledge_document
             UNION SELECT 0
         ) tenants ORDER BY tenant_id
         ON CONFLICT (tenant_id, document_id) DO UPDATE
         SET version = EXCLUDED.version, force_rebuild = true, failures = 0, next_attempt_at = now()', TG_TABLE_SCHEMA);
    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS pms_kb_search_sync_row ON pms_knowledge_document;
CREATE TRIGGER pms_kb_search_sync_row
    AFTER INSERT OR DELETE OR UPDATE OF id, tenant_id, library_id, permission_id, status, deleted, search_text
    ON pms_knowledge_document FOR EACH ROW EXECUTE FUNCTION pms_kb_enqueue_search_sync();

DROP TRIGGER IF EXISTS pms_kb_search_sync_truncate ON pms_knowledge_document;
CREATE TRIGGER pms_kb_search_sync_truncate
    BEFORE TRUNCATE ON pms_knowledge_document FOR EACH STATEMENT EXECUTE FUNCTION pms_kb_enqueue_search_truncate();

COMMIT;
